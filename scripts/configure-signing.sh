#!/bin/sh
# Writes Config/Local.xcconfig with this Mac's Apple Development signing identity.
# See docs/SIGNING.md. Safe to re-run.
set -eu
cd "$(dirname "$0")/.."

line=$(security find-identity -v -p codesigning | grep '"Apple Development:' | head -1 || true)
if [ -z "$line" ]; then
    echo "No 'Apple Development' identity found." >&2
    echo "Xcode → Settings → Accounts → add your Apple ID → Manage Certificates → + → Apple Development." >&2
    exit 1
fi
hash=$(echo "$line" | awk '{print $2}')
name=$(echo "$line" | sed -E 's/^[^"]*"(.*)"$/\1/')
team=$(security find-certificate -c "$name" -p | openssl x509 -noout -subject -nameopt multiline | awk -F' = ' '/organizationalUnitName/ {print $2; exit}')

cat > Config/Local.xcconfig <<XC
// Generated by scripts/configure-signing.sh — not committed.
CODE_SIGN_IDENTITY = $hash
DEVELOPMENT_TEAM = $team
XC
echo "Signing with: $name (team $team)"
